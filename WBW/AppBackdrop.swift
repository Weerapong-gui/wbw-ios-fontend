import SwiftUI

/// พื้นหลังกลางของแอป — **ภาพเดียวกับ `bg.jpg` ของแอป Android** (ยกมา 2026-08-20)
///
/// แยกเป็นไฟล์เดียวเพราะถูกวาดสองที่ที่ต้องตรงกันเป๊ะ: `RootView` วาดไว้ใต้ทุกอย่าง และ
/// `forestBackground` วาดในกรอบของแต่ละจอ (จำเป็น ดูคอมเมนต์ TabRootOpaqueBackgroundRemover)
/// ถ้าสองที่นี้ใช้คนละภาพหรือคนละวิธีย่อ จะเห็นรอยต่อตรงขอบแท็บทันที
///
/// **ภาพใบนี้ไม่ใช่ภาพถ่าย** — เป็นเขียวไล่เฉดที่เบลอหนักพร้อมเกรน 736×1471 (อัตราส่วน 1:2 พอดี
/// เหมือนใบเดิม) ความสว่างเฉลี่ย 0.249 · ไม่มีรายละเอียดให้เสีย การขยายขึ้นไปเต็มจอ 3x จึงไม่พร่า
/// ทั้ง palette ของ Android ถูก derive มาจากภาพใบนี้ (hue 110–146 กลาง ~130, sat 15–22%,
/// luminance 16–38%) — เปลี่ยนภาพเมื่อไหร่สีทั้งชุดใน `Config.swift` ก็ไม่ตรงกับพื้นอีกต่อไป
struct AppBackdrop: View {
    /// ฟิล์มบาง ๆ ที่ทาทับภาพเพื่อให้มันนิ่งลงใต้เนื้อหา
    ///
    /// **บางแทบไม่มี โดยตั้งใจ** — กฎข้อหนึ่งของ palette ฝั่ง Android คือ *"The image is the design;
    /// it is shown, not tinted."* ภาพพื้นหลังคือของที่แข็งแรงที่สุดของแอป อะไรที่หนักพอจะย้อมมันได้
    /// คือการทำลายสิ่งที่มันมีไว้ช่วย · โหมดสว่างไม่ทาอะไรเลย (`Color.Transparent` ที่ต้นทาง) —
    /// เคยมีรุ่นที่ทาขาวเพื่อปลอมเป็นเวอร์ชันกลางวัน แล้วอาร์ตแบนกลายเป็นเทาจนหมดเหตุผลที่จะมีภาพ
    ///
    /// **ค่าเดิม 0.35 ทั้งใบ + ไล่หัว 0.50 / ท้าย 0.45 ถูกถอดทิ้ง** — ค่าชุดนั้นจูนไว้กับภาพป่า
    /// กลางคืนที่คมและมีรายละเอียดแย่งเนื้อหาตลอดเวลา ภาพใบใหม่เบลอและสม่ำเสมออยู่แล้ว
    /// ทาหนักเท่าเดิมได้แค่พื้นเทาเรียบ ๆ ที่ไม่เหลือความเป็นภาพ
    private var wash: some View {
        Color.black
            .opacity(0.12)
            .ignoresSafeArea()
            .allowsHitTesting(false)
    }

    var body: some View {
        // **`Color.clear` เป็นตัวกำหนดขนาด ไม่ใช่ตัวภาพ** — `Color.clear` รับข้อเสนอขนาดเท่าไร
        // ก็รายงานเท่านั้นเสมอ ส่วน `.overlay` ไม่มีวันดันขนาดของสิ่งที่มันทับอยู่ ภาพจึงล้นได้
        // ตามใจแล้วโดน `.clipped()` ตัดทิ้ง โดยไม่มีทางไปยุ่งกับ layout ของใคร
        //
        // เดิมเป็น `Image(...).scaledToFill().frame(maxWidth: .infinity, maxHeight: .infinity)`
        // ซึ่งเอาอยู่บน iPhone แต่ **พังหนักบน iPad**: `frame(max…: .infinity)` ไม่ได้บังคับ
        // ขนาดให้เท่าข้อเสนอ มันแค่ยอมโตจนเต็ม — พอ `scaledToFill` รายงานขนาดตามอัตราส่วนภาพ
        // (736×1471 = 1:2) บนจอ 4:3 กรอบนี้จึงรายงานสูง 2063pt บนจอที่สูงจริง 1376pt
        // · ตัวนี้เป็นลูกของ `ZStack` ใน `RootView` ซึ่งคิดขนาดจากลูกที่ใหญ่ที่สุด **ทั้ง ZStack
        // จึงสูง 2063 แล้ว `MainTabView` ที่เป็นลูกอีกใบก็ถูกยืดตาม** พอ ZStack จัดกึ่งกลาง
        // เนื้อหาทุกแท็บเลยถูกดันขึ้นไปพ้นขอบบนจอ 340pt: แท็บกิจกรรมว่างเปล่าสนิท หน้าบัตร
        // โดนตัดหัวการ์ดทิ้ง หน้าแรกเหลือแต่ดอกไม้ไม่มีตัวอักษรสักบรรทัด (ยืนยันด้วย NSLog
        // ของ `frame(in: .global)` จริงบน iPad Pro 13" ไม่ใช่จากการอ่านโค้ด)
        Color.clear
            .overlay {
                Image("bg_backdrop")
                    .resizable()
                    .scaledToFill()
            }
            .clipped()
            .ignoresSafeArea()
            .overlay(wash)
    }
}
