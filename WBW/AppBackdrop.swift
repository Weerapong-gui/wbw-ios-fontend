import SwiftUI

/// พื้นหลังกลางของแอป — ภาพป่าเต็มจอ
///
/// แยกเป็นไฟล์เดียวเพราะถูกวาดสองที่ที่ต้องตรงกันเป๊ะ: `RootView` วาดไว้ใต้ทุกอย่าง และ
/// `forestBackground` วาดในกรอบของแต่ละจอ (จำเป็น ดูคอมเมนต์ TabRootOpaqueBackgroundRemover)
/// ถ้าสองที่นี้ใช้คนละภาพหรือคนละวิธีย่อ จะเห็นรอยต่อตรงขอบแท็บทันที
///
/// รูป 1440×2880 (1:2) เลือกไว้ให้อยู่ใกล้กึ่งกลางเรขาคณิตของจอที่กว้างสุด (SE 0.562) กับสูงสุด
/// (Pro Max 0.460) — `scaledToFill` ครอบเต็มแล้วตัดส่วนเกิน ออกแบบตามปลายด้านใดด้านหนึ่ง
/// จะโดนตัด 18% ด้านเดียว แบบนี้หนักสุด ~11% แนวตั้ง หรือ ~8% แนวนอน
struct AppBackdrop: View {
    /// scrim หัว-ท้าย ไม่ใช่คลุมทั้งใบ
    ///
    /// จอที่ใช้พื้นนี้ออกแบบตอนพื้นหลังยังเป็น #0A1610 เข้ม ตัวหนังสือกับไอคอนจึงเป็นสีขาวหมด
    /// (คำทักทายที่ Home, หัวข้อกับกรอบมุมที่ QR) ตอนนี้พื้นหลังเป็นภาพป่ากลางคืนซึ่งมืดอยู่แล้ว
    /// แต่ยังถอด scrim ทิ้งไม่ได้ — หัวจอของภาพมีช่องแสงลอดใบไม้ที่สว่างพอจะกลืนตัวอักษรขาว
    /// ส่วนท้ายจอต้องมีอะไรคั่นระหว่างแถบแท็บกับพื้นดินที่มีหิ่งห้อยกระพริบ ไม่งั้นแถบแท็บลอยจม
    ///
    /// **2026-08-20: เพิ่มชั้นทึบคลุมทั้งใบ** เดิมไล่เฉพาะหัวกับท้าย (0.25/0.28) แล้วปล่อยกลางจอโล่ง
    /// ด้วยเหตุผลว่า "อยากเห็นป่าเต็ม ๆ" — ผลคือของที่วางกลางจอต้องหาทางรอดกันเอง ดอกไม้ Bloom
    /// ต้องแบก `.shadow` หนา ๆ ไว้กันขอบกลืนกับใบไม้ที่โดนแสงส่อง ซึ่งเป็นการแก้ที่ปลายเหตุ
    /// และแก้ได้เฉพาะชิ้นที่นึกออกว่าต้องแก้
    ///
    /// ตอนนี้เป็นชั้นทึบ 0.35 ทั้งใบ + ไล่ทับอีกชั้นที่หัว (0.50) กับท้าย (0.45) ซึ่งเป็นที่ที่
    /// UI จริงอยู่ (header ด้านบน, แถบแท็บด้านล่าง) · ภาพยังอ่านออกว่าเป็นป่าและยังเห็นหิ่งห้อย
    /// แต่ไม่แข่งกับตัวหนังสืออีกแล้ว
    ///
    /// **เปลี่ยนภาพเมื่อไหร่ต้องมาจูนใหม่จากสกรีนช็อตจริงทุกครั้ง** (ดู AppAssetsTests)
    private var scrim: some View {
        ZStack {
            Color.black.opacity(0.35)
            LinearGradient(
                stops: [
                    .init(color: .black.opacity(0.50), location: 0.00),
                    .init(color: .black.opacity(0.00), location: 0.30),
                    .init(color: .black.opacity(0.00), location: 0.72),
                    .init(color: .black.opacity(0.45), location: 1.00),
                ],
                startPoint: .top, endPoint: .bottom
            )
        }
        .ignoresSafeArea()
        .allowsHitTesting(false)
    }

    var body: some View {
        Image("bg_ticket")
            .resizable()
            .scaledToFill()
            // frame + clipped ก่อน ignoresSafeArea — scaledToFill ทำให้ภาพล้นกรอบจริง ไม่คลิป
            // แล้วภาพส่วนเกินจะไปดันขนาดของ container แล้วเลย์เอาต์ข้างในเพี้ยนตาม
            .frame(maxWidth: .infinity, maxHeight: .infinity)
            .clipped()
            .ignoresSafeArea()
            .overlay(scrim)
    }
}
