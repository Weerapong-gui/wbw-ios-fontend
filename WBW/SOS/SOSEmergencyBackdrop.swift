import SwiftUI

/// กติกาของการเต้น — แยกออกมาเป็นตรรกะล้วนเพราะ **ภาพนิ่งพิสูจน์ไม่ได้ว่ามันเต้นถูกจังหวะไหม**
///
/// ทรงเดียวกับ `LocationPrimer.shouldShow` และ `SOSWhere.from` — จอไม่ตัดสินใจเอง
enum SOSPulse {

    /// รอบละกี่วินาที (ไป-กลับหนึ่งรอบเต็ม)
    ///
    /// ช้าพอที่จะ **ไม่ใช่ไฟกะพริบ** — เกณฑ์เรื่องแสงกระตุ้นอาการชักที่ยอมรับกันคือต่ำกว่า
    /// 3 ครั้งต่อวินาที ค่านี้อยู่ราวหนึ่งในสามครั้งต่อวินาที ห่างเกณฑ์อยู่มาก · จอฉุกเฉิน
    /// ต้องไม่กลายเป็นตัวกระตุ้นอาการของใครกลางเหตุการณ์จริง
    static let cycleSeconds: Double = 1.6

    /// เต้นเมื่อเคสยังเปิดอยู่เท่านั้น
    ///
    /// รวม `.onTheWay` ด้วยตามที่เจ้าของงานสั่ง (เต้นต่อจนเคสปิด) — คนที่กำลังเดินมาหาต้องเห็น
    /// เครื่องเรืองแดงจากไกลเหมือนเดิม การหยุดเต้นตอนเจ้าหน้าที่กดรับจึงเป็นการดับสัญญาณ
    /// ตอนที่มันยังมีประโยชน์ที่สุด · `.closed`/`nil` = จบแล้ว ต้องเลิกส่งสัญญาณทันที
    static func pulses(status: SOSStatus?) -> Bool {
        status?.isActive ?? false
    }

    /// ช่วงความทึบของแดงที่ขอบจอ
    ///
    /// ต่ำสุด **ไม่ลงไปถึงศูนย์** — จังหวะที่จางที่สุดต้องยังอ่านออกว่าเป็นจอฉุกเฉิน ไม่ใช่จอดำ
    /// ธรรมดาที่บังเอิญแดงเป็นพัก ๆ · เปิด Reduce Motion คืนจุดเดียว (นิ่งสนิทที่ค่ากลาง)
    /// ไม่ใช่ช่วงที่แคบลง — คนที่เปิดตัวเลือกนี้มักเปิดเพราะการเคลื่อนไหวทำให้เวียนหัวหรือ
    /// กระตุ้นอาการ ซึ่งเป็นสิ่งสุดท้ายที่ควรเจอตอนกำลังเจ็บอยู่ (แอปนี้เคารพค่านี้อยู่แล้วที่
    /// `IntroView`, `Map3DScreen`, `GrowingTree`)
    static func opacityRange(reduceMotion: Bool) -> ClosedRange<Double> {
        reduceMotion ? 0.8...0.8 : 0.55...1.0
    }

    /// ความทึบ ณ เวลาหนึ่ง — **คำนวณจากนาฬิกา ไม่ใช่จาก state ที่สลับครั้งเดียวตอน `onAppear`**
    ///
    /// ของเดิมใช้ `@State` สลับทีเดียวแล้วให้ `.repeatForever` วิ่งต่อ ซึ่งพังเงียบบนจอบัตร:
    /// วิวถูกสร้างตั้งแต่ตอนที่ยังไม่มีเคส (`pulsing == false`) พอเคสเปิดทีหลัง ตัวแปรที่ผูก
    /// animation ไว้ไม่ได้เปลี่ยนค่าอีกแล้ว การเต้นจึงไม่เคยเริ่ม — สกรีนช็อตสองใบห่างกันหนึ่ง
    /// วินาทีได้สีมุมจอเท่ากันเป๊ะทุกช่อง ซึ่งเป็นอาการที่จับได้จากภาพเท่านั้น
    ///
    /// คิดจากเวลาแล้วจังหวะจะถูกเสมอไม่ว่าวิวจะถูกสร้างตอนไหน และเทสตรวจได้ตรง ๆ
    static func opacity(at time: TimeInterval, reduceMotion: Bool) -> Double {
        let range = opacityRange(reduceMotion: reduceMotion)
        guard range.lowerBound < range.upperBound else { return range.lowerBound }
        // sin คืน -1...1 → ยืดเป็น 0...1 แล้วแมปลงช่วงความทึบ · ไซน์ให้จังหวะ "หายใจ"
        // ที่ไม่มีหัวมุมกระตุกตอนกลับทาง ต่างจากเส้นตรงที่สลับทิศทันที
        let unit = (sin(2 * .pi * time / cycleSeconds) + 1) / 2
        return range.lowerBound + unit * (range.upperBound - range.lowerBound)
    }
}

/// พื้นหลังของจอสถานะ SOS — แดงเข้มที่ขอบจอ ไล่จางเข้าหากลางจอ
///
/// **ขอบเรือง ไม่ใช่ถมแดงทั้งจอ** โดยตั้งใจ: จอนี้ถูกออกแบบมาให้ยื่นให้คนอื่นอ่าน (การ์ด
/// กรุ๊ปเลือด/เบอร์ญาติ กับสถานะว่าเจ้าหน้าที่รับเรื่องหรือยัง) ถมแดงทั้งจอแปลว่าต้องรื้อสี
/// ตัวอักษรทั้งจอตาม และการ์ดที่คนอื่นต้องอ่านจะกลายเป็นตัวหนังสือบนพื้นแดง · เรืองจากขอบ
/// ทำหน้าที่ที่ต้องการได้ครบ — มองออกจากระยะไกลและจากหางตาว่าเครื่องนี้กำลังรอความช่วยเหลือ
/// — โดยไม่แตะการอ่านตรงกลางจอเลย
///
/// **ไม่กินสัมผัส** (`allowsHitTesting(false)`) — ทุกปุ่มบนจอนี้แพงเกินกว่าจะเสี่ยงให้พื้นหลัง
/// มาแย่งแตะ โดยเฉพาะปุ่มยกเลิกที่แปลว่า "เจ้าหน้าที่ไม่ต้องวิ่งขึ้นเขาแล้ว"
struct SOSEmergencyBackdrop: View {
    let pulsing: Bool
    let reduceMotion: Bool

    var body: some View {
        // `TimelineView` แทน `@State` + `.repeatForever` — เหตุผลเต็มที่ `SOSPulse.opacity(at:)`
        // · `paused` ตอนไม่มีเคส เพื่อไม่ให้จอที่ไม่มีอะไรเกิดขึ้นเสียแบตกับ redraw ทุกเฟรม
        TimelineView(.animation(minimumInterval: 0.05, paused: !pulsing)) { context in
            // กลางจอโปร่งสนิท ปล่อยพื้นเดิมของแอปทะลุขึ้นมา แล้วค่อยเข้มขึ้นเรื่อย ๆ จนถึงขอบ
            // · `.screen` ทำให้แดงเรืองซ้อนบนพื้นที่มีอยู่แทนที่จะทับทึบ ขอบจอจึงดู "เรือง"
            // ไม่ใช่ "ทาสี" — สำคัญบนจอบัตรซึ่งมีพื้นป่าอยู่ข้างหลัง
            RadialGradient(
                colors: [.clear, Color.wbwEmergencyEdge.opacity(0.35), Color.wbwEmergencyEdge],
                center: .center,
                startRadius: 40,
                endRadius: 620,
            )
            .blendMode(.screen)
            .opacity(pulsing
                     ? SOSPulse.opacity(at: context.date.timeIntervalSinceReferenceDate,
                                        reduceMotion: reduceMotion)
                     : 0)
        }
        .ignoresSafeArea()
        .allowsHitTesting(false)
    }
}
