import Foundation

/// ความเห็นทั้งงาน (event feedback) — ให้คะแนนภาพรวม "ทั้งเดิน" ครั้งเดียวตอนจบทริป
/// ต่างจาก `FeedbackDraft` (ความเห็นต่อฐาน) สองจุด:
///
/// 1) **ไม่มี `checkpointId`** — ไม่ผูกกับฐานไหนเลย เป็นคำถามระดับงาน ไม่ใช่ระดับจุด · `ratingActivity`
///    (กิจกรรมตลอดเส้นทาง) คือข้อที่ย้ายมาจากฟอร์มต่อฐานของ Android มาไว้ที่นี่แทน — ฟอร์มต่อฐาน
///    เลิกถามข้อนี้แล้วแต่ยังเก็บฟิลด์ไว้เผื่อ draft เก่าค้างคิว (ดูคอมเมนต์ที่ `FeedbackOutbox.swift`)
///
/// 2) **ไม่มี outbox/คิว** — ต่างจากความเห็นต่อฐานที่เก็บเข้าคิวแล้วปิดฟอร์มทันทีเพราะยังมีฐานถัดไป
///    ให้เดินต่อ (จะ retry รอบหน้าตอน flush ก็ยังทัน) ฟอร์มนี้คือจอสุดท้ายก่อนจบทริป ไม่มี "รอบหน้า"
///    ให้แอบ retry เงียบๆ — ตามสเปก ฟอร์มค้างอยู่บนจอเองจนกว่าจะส่งสำเร็จหรือผู้ใช้กดข้ามเอง ผู้ใช้
///    จึงต้องเห็นผลจริงทันที (`FeedbackSubmitOutcome`) ไม่ใช่ "ดูเหมือนส่งแล้ว" ที่จริงยังค้างในคิว
struct EventFeedbackDraft: Codable, Equatable {
    let clientId: String
    let rating: Int                 // ภาพรวมทั้งเดิน — ข้อเดียวที่บังคับ
    var ratingActivity: Int?        // กิจกรรมตลอดเส้นทาง — ข้อที่ย้ายมาจากต่อฐาน
    let comment: String?
    let deviceTime: String
}
