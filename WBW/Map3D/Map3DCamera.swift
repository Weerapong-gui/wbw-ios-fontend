import Foundation
import simd

/// กล้องของแท็บแผนที่ — คุมเองแทน `.realityViewCameraControls(.orbit)`
///
/// `.orbit` ให้ผู้ใช้หมุนได้อิสระรวมถึงมุดลงไปมองใต้โมเดล (เห็นก้นภูมิประเทศเป็นแผ่นแบนๆ)
/// และไม่มี API ให้จำกัดมุมหรือกำหนดทิศเริ่มต้น จึงต้องเขียนเอง ตรรกะทั้งหมดอยู่ในนี้เป็น
/// ฟังก์ชันบริสุทธิ์ให้เทสได้ ตัว `Map3DScreen` แค่เอาค่าที่ได้ไปตั้ง `PerspectiveCamera`
///
/// ทุกมุมเป็นเรเดียน · ระยะเป็นหน่วยของฉากหลังโมเดลถูกย่อให้พอดีกรอบ 2 หน่วยแล้ว
enum Map3DCamera {
    /// มุมกวาดเริ่มต้น — หันด้านหน้ามหาวิทยาลัยเข้าหากล้อง
    ///
    /// ค่านี้หาจากการถ่ายจริงเทียบกับภาพอ้างอิงที่ Park ให้ ไม่ได้คำนวณจากทิศเหนือจริง
    /// (ปรับได้ตอนรันด้วย `-uitestMapHeading <องศา>` เพื่อถ่ายเทียบหลายค่า)
    static let defaultYaw: Float = 0

    /// ตัวเลขทุกตัวข้างล่างมาจาก `WBW/Resources/map_config.json` — โมเดลจะถูกเปลี่ยนใบ
    /// ขอบเขตกล้องต้องจูนใหม่ตามโมเดลเสมอ ปล่อยไว้ในโค้ดแล้วต้อง build ใหม่ทุกครั้งที่ลองค่า
    private static var camera: Map3DConfig.Camera { Map3DConfig.current.camera }

    /// มุมเงยเริ่มต้น
    ///
    /// ⚠️ ทิศทางที่ถ่ายเทียบได้จริง (หลังใส่โดมฟ้า ภาพอ่านออกทุกมุมแล้ว):
    /// **ค่าน้อย = กล้องต่ำ เกือบระดับสายตา แผ่นภูมิประเทศอ่านเป็นแผ่นบาง ·
    /// ค่ามาก = มองเกือบจากบนหัว โมเดลราบเต็มจอ** — ตรงกับสูตร `position` (y = distance·sin(pitch))
    ///
    /// คอมเมนต์เดิมตรงนี้เขียนกลับด้าน (อ้างว่า 8° = มองจากบนหัว) เพราะตอนนั้นยังไม่มีโดมฟ้า
    /// มุมต่ำจึงเห็นแต่พื้นดำกับแถบน้ำตาลจนตีความภาพผิด · เคยลองสลับสูตรให้ Z เป็นแกนความสูงตาม
    /// สมมติฐานว่าฉากเป็น Z-up แล้วพังซ้ำ จึงคืนสูตร Y-up เดิม **ห้ามแตะสูตร** แก้ได้แค่ตัวเลข
    /// ใน JSON และต้องถ่ายภาพเทียบก่อนเสมอ
    static var defaultPitch: Float { camera.defaultPitchDegrees * .pi / 180 }

    /// ปลายทางฝั่ง **"กล้องต่ำ เกือบระดับสายตา"** — นี่คือข้อที่กันไม่ให้เห็นขอบโมเดล
    ///
    /// ไล่มาสามรอบ: 6° → 12° (ตอนใส่โดมฟ้า) → **34° (2026-08-20)**
    ///
    /// ที่ 6° กล้องเกือบขนานกับแผ่น ภูมิประเทศอ่านเป็น "แผ่นบางลอยกลางฟ้า" มีสันตัดพาดขวางจอ
    /// (วัดสีได้ (10,22,16) เกือบดำ) · ที่ 12° กับ 22° ยังเห็นสันตัดของ **ขอบใกล้** เป็นแถบเข้ม
    /// พาดกลางจอ พร้อมพื้นที่นอกกรอบโมเดลโผล่อยู่ใต้แถบนั้น (ถ่ายจริง 2026-08-20 ทั้งสองมุม)
    ///
    /// เหตุผลเชิงเรขาคณิต: ที่มุมต่ำกล้องอยู่ห่างศูนย์กลางตามแนวราบเกินครึ่งความกว้างของแผ่น
    /// = ยืนอยู่ "นอก" ขอบโมเดล ขอบใกล้จึงเข้ามาอยู่ในเฟรมเสมอ ไม่มีม่านหรือชายพื้นไหนปิดได้
    /// โดยไม่บังภูมิประเทศไปด้วย · ตั้งแต่ราว 30° ขึ้นไปขอบใกล้หลุดลงไปอยู่ใต้แถบแท็บ
    /// เผื่อไว้ที่ 34° ให้ห่างจากค่าที่วัดได้จริง
    static var minPitch: Float { camera.minPitchDegrees * .pi / 180 }

    /// ปลายทางฝั่ง **"มองเกือบจากบนหัว"** — เกินกว่านี้ภาพแบนจนไม่เหลือความเป็นสามมิติ
    ///
    /// ⚠️ ชื่อ min/max ตรงข้ามกับสิ่งที่เห็นบนจอ ดูคำเตือนที่ `defaultPitch`
    /// เทส Map3DCameraTests คุมไว้ว่าค่านี้ต้องไม่ถึง 90°
    static var maxPitch: Float { camera.maxPitchDegrees * .pi / 180 }

    static var minDistance: Float { camera.minDistance }
    static var maxDistance: Float { camera.maxDistance }
    static var defaultDistance: Float { camera.defaultDistance }

    /// ท่ากล้องตอนจ้องหมุด — เงยต่ำกว่าค่าเริ่มต้นเพื่อให้เห็นฐานเป็นทรงสามมิติ ไม่ใช่มองจากบนหัว
    static var focusPitch: Float { camera.focusPitchDegrees * .pi / 180 }
    static var focusDistance: Float { camera.focusDistance }
    /// ความเร็วหมุนวนรอบฐาน เรเดียนต่อวินาที
    static var orbitSpeed: Float { camera.orbitDegreesPerSecond * .pi / 180 }

    /// **หมุนได้รอบตัว** — เดิมล็อกไว้ ±55° จากมุมเริ่มต้น (`yawRange`) เจ้าของงานสั่งให้ปลดล็อก
    ///
    /// wrap เข้าช่วง (-π, π] ไม่ใช่ปล่อยให้ค่าสะสมโตไปเรื่อย ๆ: ค่านี้เป็นจุดตั้งต้นของท่าทางลาก
    /// รอบถัดไป (`gestureStartYaw`) และเป็นปลายทางของแอนิเมชันบินเข้าหาหมุด — ปล่อยให้เป็น
    /// หลักพันเรเดียนแล้วเส้นโค้ง interpolate จะวิ่งวนหลายรอบก่อนถึงที่หมาย
    static func wrapYaw(_ yaw: Float) -> Float {
        let full = 2 * Float.pi
        // remainder(dividingBy:) คืนช่วง [-π, π] ปิดทั้งสองข้าง — บังคับ -π ให้เป็น +π
        // เพื่อให้ทิศเดียวกันได้ค่าเดียวกันเสมอ (ไม่งั้น 180° กับ -180° เป็นคนละค่าทั้งที่ชี้ทางเดียวกัน)
        let wrapped = yaw.remainder(dividingBy: full)
        return wrapped <= -Float.pi + 1e-6 ? wrapped + full : wrapped
    }

    static func clampPitch(_ pitch: Float) -> Float {
        min(max(pitch, minPitch), maxPitch)
    }

    /// `floor` = ระยะใกล้สุดที่ยอมให้ · ปล่อยว่าง = `minDistance` (ขอบของท่าทางผู้ใช้)
    ///
    /// ต้องรับ floor เข้ามาได้เพราะ **การซูมตอนโฟกัสหมุดเข้าใกล้กว่าที่ผู้ใช้ลากเองได้ โดยตั้งใจ**
    /// `minDistance` ถูกจูนไว้กับการมองทั้งแผนที่ (เป้าอยู่กลางโมเดล ใกล้กว่านี้กล้องจะจมเข้าไปใน
    /// เนื้อภูมิประเทศตอน pitch ต่ำ) แต่ตอนโฟกัสเป้าคือแท่งหมุดซึ่งอยู่บนผิว ระยะเท่ากันจึงไม่ได้
    /// แปลว่าอยู่ที่เดียวกัน · บังคับ floor เดียวกันทั้งสองกรณีแล้วจะได้อย่างใดอย่างหนึ่ง:
    /// โฟกัสไกลจนไม่รู้ว่าซูมเข้า หรือผู้ใช้ลากจนกล้องมุดเข้าไปในภูเขา
    static func clampDistance(_ distance: Float, floor: Float? = nil) -> Float {
        min(max(distance, floor ?? minDistance), maxDistance)
    }

    /// ตำแหน่งกล้องบนทรงกลมรอบจุดที่มอง
    ///
    /// pitch 0 = ระดับสายตาเดียวกับเป้า · pitch สูงขึ้น = ลอยสูงขึ้นและเข้าใกล้แนวดิ่ง
    static func position(yaw: Float, pitch: Float, distance: Float,
                         target: SIMD3<Float>) -> SIMD3<Float> {
        let horizontal = distance * cos(pitch)
        return SIMD3<Float>(
            target.x + horizontal * sin(yaw),
            target.y + distance * sin(pitch),
            target.z + horizontal * cos(yaw)
        )
    }
}
